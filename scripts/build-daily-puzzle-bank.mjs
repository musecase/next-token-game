import fs from "node:fs";

const reviewFiles = [1, 2, 3, 4].map((number) => new URL(`../daily-three-review-0${number}.md`, import.meta.url));
const start = new Date("2026-08-15T12:00:00Z");
const difficulties = ["gentle", "tricky", "devious"];
const puzzles = [];
const sets = [];

for (const reviewFile of reviewFiles) {
  const source = fs.readFileSync(reviewFile, "utf8");
  const rows = [...source.matchAll(/^\| (\d{3}) \| \[.\] (.*?) → \*\*([^*]+)\*\* \| \[.\] (.*?) → \*\*([^*]+)\*\* \| \[.\] (.*?) → \*\*([^*]+)\*\* \|$/gm)];

  for (const row of rows) {
    const day = Number(row[1]);
    const expectedDay = sets.length + 1;
    if (day !== expectedDay) throw new Error(`Expected day ${expectedDay}, found ${day}.`);

    const date = new Date(start);
    date.setUTCDate(date.getUTCDate() + day - 1);
    const dateKey = date.toISOString().slice(0, 10);
    const cells = [[row[2], row[3]], [row[4], row[5]], [row[6], row[7]]];
    const puzzleIds = [];

    cells.forEach(([question, target], index) => {
      const id = `d${String(day).padStart(3, "0")}-${difficulties[index][0]}`;
      puzzles.push({ id, date: dateKey, question, target, difficulty: difficulties[index] });
      puzzleIds.push(id);
    });
    sets.push({ date: dateKey, puzzleIds });
  }
}

if (sets.length !== 365 || puzzles.length !== 1095) {
  throw new Error(`Expected 365 sets and 1095 puzzles; found ${sets.length} and ${puzzles.length}.`);
}

const output = `// Generated by scripts/build-daily-puzzle-bank.mjs from the reviewed Markdown files.\n` +
  `// Edit the review files and regenerate instead of hand-editing this file.\n\n` +
  `export const GENERATED_DAILY_PUZZLES = ${JSON.stringify(puzzles, null, 2)} as const;\n\n` +
  `export const GENERATED_DAILY_SETS = ${JSON.stringify(sets, null, 2)} as const;\n`;

fs.writeFileSync(new URL("../app/daily-puzzles.generated.ts", import.meta.url), output);
console.log(`Generated ${puzzles.length} puzzles in ${sets.length} daily sets.`);
